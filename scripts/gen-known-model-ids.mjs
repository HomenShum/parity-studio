#!/usr/bin/env node
// Regenerates convex/lib/knownModelIds.generated.ts from the installed pi-ai catalog.
// The Convex V8 runtime (convex/runs.ts) cannot import pi-ai, so the public model-selection boundary
// (model-defaults SPEC A.0.10) checks against this snapshot; convex/lib/modelBoundary.test.ts fails when it drifts.
//   node scripts/gen-known-model-ids.mjs && pnpm exec biome format --write convex/lib/knownModelIds.generated.ts
import { writeFileSync } from 'node:fs';
import { getModels } from '@earendil-works/pi-ai/compat';

const PROVIDERS = [
  'anthropic',
  'openai',
  'google',
  'openrouter',
  'groq',
  'cerebras',
  'xai',
  'mistral',
];
const entries = PROVIDERS.map(
  (p) =>
    `  ${p}: [${getModels(p)
      .map((m) => JSON.stringify(m.id))
      .sort()
      .join(', ')}],`,
);
writeFileSync(
  new URL('../convex/lib/knownModelIds.generated.ts', import.meta.url),
  `// GENERATED by scripts/gen-known-model-ids.mjs from the installed @earendil-works/pi-ai catalog. Do not edit.\nexport const KNOWN_MODEL_IDS: Readonly<Record<string, readonly string[]>> = {\n${entries.join('\n')}\n};\n`,
);
